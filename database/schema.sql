CREATE DATABASE IF NOT EXISTS `01_epbls_db` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `01_epbls_db`;

CREATE TABLE IF NOT EXISTS `users` (
  UserID INT AUTO_INCREMENT PRIMARY KEY,
  FullName VARCHAR(100) NOT NULL,
  Email VARCHAR(160) NOT NULL UNIQUE,
  PasswordHash VARCHAR(255) NOT NULL,
  Role VARCHAR(30) NOT NULL DEFAULT 'user',
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `permit_types` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `PermitName` VARCHAR(255) NOT NULL,
  `Description` TEXT NULL,
  `Fee` DECIMAL(12,2) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `applications` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `BusinessName` VARCHAR(255) NOT NULL,
  `Status` ENUM('pending','approved','rejected') NULL,
  `SubmittedAt` DATETIME NULL,
  `UserID` INT NOT NULL,
  `PermitTypeID` INT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `fk_applications_userid` FOREIGN KEY (`UserID`) REFERENCES `users` (`UserID`) ON DELETE RESTRICT,
  CONSTRAINT `fk_applications_permittypeid` FOREIGN KEY (`PermitTypeID`) REFERENCES `permit_types` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `payments` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `Amount` DECIMAL(12,2) NOT NULL,
  `PaymentMethod` VARCHAR(255) NOT NULL,
  `PaidAt` DATETIME NULL,
  `ApplicationID` INT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `fk_payments_applicationid` FOREIGN KEY (`ApplicationID`) REFERENCES `applications` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `application_documents` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `FileName` VARCHAR(255) NOT NULL,
  `FilePath` VARCHAR(255) NOT NULL,
  `UploadedAt` DATETIME NULL,
  `ApplicationID` INT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `fk_application_documents_applicationid` FOREIGN KEY (`ApplicationID`) REFERENCES `applications` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
